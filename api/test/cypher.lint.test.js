/**
 * cypher.lint.test.js - checks every Cypher statement in the project with Neo4j's own
 * Cypher parser and semantic analyser (@neo4j-cypher/language-support): the .cypher scripts
 * in db/ AND every statement the API generates at run time.
 */
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const request = require('supertest');
const { lintCypherQuery } = require('@neo4j-cypher/language-support');
const { parseCypherFile } = require('../src/queries');
const { createApp } = require('../src/app');
const { fakeDb } = require('./fakeDb');
const { ENTITIES, RELATIONSHIPS } = require('../src/schema');

const DB_DIR = path.join(__dirname, '..', '..', 'db');
// This project's labels and relationship types, so that a misspelt label (e.g. :Suspects) or
// relationship type is reported too.
const SCHEMA = {
  labels: ['Suspect', 'Crime', 'Location', 'Evidence', 'Officer'],
  relationshipTypes: ['KNOWS', 'COMMITTED', 'OCCURRED_AT', 'LINKED_TO', 'INVESTIGATING', 'FOUND_AT'],
};
// every error AND every warning (cartesian products, unbounded paths, unknown labels ...) fails the test
const errorsOf = (q) => lintCypherQuery(q, SCHEMA);

function plainStatements(file) {
  return fs.readFileSync(path.join(DB_DIR, file), 'utf8').replace(/^\s*\/\/.*$/gm, '')
    .split(';').map((s) => s.trim()).filter(Boolean);
}

const scripts = [
  ...plainStatements('01_schema.cypher').map((c, i) => ({ where: `01_schema #${i + 1}`, cypher: c })),
  ...plainStatements('99_reset.cypher').map((c) => ({ where: '99_reset', cypher: c })),
  ...['02_load_unwind.cypher', '03_crud.cypher', '04_queries.cypher', '05_indexes.cypher']
    .flatMap((f) => parseCypherFile(path.join(DB_DIR, f)).map((q) => ({ where: `${f} ${q.name}`, cypher: q.cypher }))),
  ...plainStatements('02_load_csv.cypher').map((c, i) => ({ where: `02_load_csv #${i + 1}`, cypher: c })),
];

test(`all ${scripts.length} statements in db/*.cypher are valid Cypher`, { timeout: 120000 }, () => {
  const bad = scripts.map((s) => ({ ...s, errors: errorsOf(s.cypher) })).filter((s) => s.errors.length);
  assert.deepEqual(bad.map((b) => `${b.where}: ${b.errors.map((e) => e.message).join('; ')}`), []);
  assert.ok(scripts.length >= 90);
});

test('every statement generated by the API is valid Cypher', { timeout: 120000 }, async () => {
  const db = fakeDb((c) => ({ rows: [{ total: 0, items: [], n: { x: 1 }, relationships: [], rels: 0, hasFrom: true, hasTo: true, linked: [], hasCrime: true, hasOfficer: true, previous: [], deleted: 1, properties: {} }] }));
  const app = createApp(db);
  for (const e of Object.keys(ENTITIES)) {
    const key = ENTITIES[e].key;
    await request(app).get(`/api/${e}?${ENTITIES[e].filters[0]}=x`);
    await request(app).get(`/api/${e}/ID1`);
    await request(app).post(`/api/${e}`).send({ [key]: 'x' });
    await request(app).patch(`/api/${e}/ID1`).send({ [Object.keys(ENTITIES[e].props)[1]]: 'x' });
    await request(app).delete(`/api/${e}/ID1?detach=true`);
  }
  for (const t of Object.keys(RELATIONSHIPS)) {
    await request(app).get(`/api/relationships/${t}?from=a`);
    await request(app).post(`/api/relationships/${t}`).send({ from: 'a', to: 'b' });
    await request(app).patch(`/api/relationships/${t}`).send({ from: 'a', to: 'b', properties: { [Object.keys(RELATIONSHIPS[t].props)[0]]: null } });
    await request(app).delete(`/api/relationships/${t}?from=a&to=b`);
  }
  await request(app).post('/api/cases').send({ crime: { crime_id: 'CR031', type: 'Fraud', date: '2026-09-10' }, location_id: 'L1', lead_officer: 'B1' });
  await request(app).patch('/api/cases/CR001/lead').send({ badge_number: 'B1201' });
  await request(app).post('/api/demo/rollback');
  await request(app).get('/api/health');
  const generated = [...new Set(db.cyphers())];
  const bad = generated.map((c) => ({ c, e: errorsOf(c) })).filter((x) => x.e.length);
  assert.deepEqual(bad.map((b) => `${b.c}\n  -> ${b.e.map((e) => e.message).join('; ')}`), []);
  assert.ok(generated.length >= 40, `only ${generated.length} statements generated`);
});
